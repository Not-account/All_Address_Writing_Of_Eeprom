/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
    HAL_Init();

    SystemClock_Config();

    MX_GPIO_Init();

    MX_I2C1_Init();


    /*
     * Initialize LCD
     */
    LCD_Init();

    LCD_Clear();


    /*
     * Check EEPROM
     */
    if (EEPROM_IsReady() != HAL_OK)
    {
        LCD_SetCursor(0, 0);
        LCD_Print("EEPROM ERROR");

        while (1)
        {
        }
    }


    /*
     * Data to write
     */
    uint8_t write_data[2];

    write_data[0] = 0xFF;
    write_data[1] = 0xFF;


    /*
     * Write FF FF
     *
     * EEPROM address:
     * 0x0000
     */
    if (EEPROM_Write(0x0000,
                     write_data,
                     2) != HAL_OK)
    {
        LCD_Clear();

        LCD_SetCursor(0, 0);
        LCD_Print("WRITE ERROR");

        while (1)
        {
        }
    }


    /*
     * Wait for EEPROM
     */
    HAL_Delay(10);


    /*
     * Read data
     */
    uint8_t read_data[2];

    read_data[0] = 0x00;
    read_data[1] = 0x00;


    if (EEPROM_Read(0x0000,
                    read_data,
                    2) != HAL_OK)
    {
        LCD_Clear();

        LCD_SetCursor(0, 0);
        LCD_Print("READ ERROR");

        while (1)
        {
        }
    }


    /*
     * Display result
     */
    LCD_Clear();


    /*
     * First line:
     *
     * ADDR:0000
     */
    LCD_SetCursor(0, 0);

    LCD_Print("ADDR:0000");


    /*
     * Second line:
     *
     * DATA:FF FF
     */
    LCD_SetCursor(1, 0);

    LCD_Print("DATA:");

    LCD_PrintHex8(read_data[0]);

    LCD_Print(" ");

    LCD_PrintHex8(read_data[1]);


    while (1)
    {
        HAL_Delay(1000);
    }
}
